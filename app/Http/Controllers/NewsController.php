    /*
	* force download news attachment
	* @param string $subdomain
	* @param string $url
	* @return Illuminate\View\View
	*/
    public function getForceDownload($subdomain, $url)
    {
        $officeId    = Office::getIdfromSubdomain($subdomain);
        $languageId = Language::getIdFromCode();
        $sessionLangId = (Session::get('language_id')) ? Session::get('language_id') : $languageId;
        Session::put('language_id', $sessionLangId);

        try {
            $newsData    = News::getNewsDetail($officeId, $url, $sessionLangId);
            if (
                $newsData &&
                !empty($newsData->news_attachment) &&
                basename($newsData->news_attachment) === $newsData->news_attachment &&
                is_file(public_path() . '/uploads/news/' . $newsData->news_attachment) &&
                is_readable(public_path() . '/uploads/news/' . $newsData->news_attachment)
            ) {
                $file = public_path() . '/uploads/news/' . $newsData->news_attachment;
                $ext = pathinfo($file, PATHINFO_EXTENSION);
                $fileName = $newsData->news_heading . '.' . $ext;
                DB::table('news')
                    ->where('id', $newsData->id)
                    ->increment('download_count', 1);

                $headers = array(
                    'Content-Type: application/' . $ext,
                );
                $response = Response::download($file, $fileName);
                if (ob_get_level() > 0) {
                    ob_end_clean();
                }
                return  $response;
            } else {
                $seoDetail    = Seo::getSeoDetailsByPageNameAndLanguage('error', $sessionLangId);
                return view(
                    'home.404',
                    array(
                        'pageTitle' => $seoDetail->page_title,
                        'metaDescription' => $seoDetail->meta_tags,
                        'metaKeywords' => $seoDetail->meta_description,
                        'abs_site_url' => $this->abs_site_url,
                        'rel_site_url' => $this->rel_site_url,
                        'site_name' => $this->site_name,
                        'subdomain' => $subdomain
                    )
                );
            }
        } catch (Throwable $e) {
            $seoDetail    = Seo::getSeoDetailsByPageNameAndLanguage('error', $sessionLangId);
            return view(
                'home.404',
                array(
                    'pageTitle' => $seoDetail->page_title,
                    'metaDescription' => $seoDetail->meta_tags,
                    'metaKeywords' => $seoDetail->meta_description,
